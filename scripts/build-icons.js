// Builds a small icon sprite from Phosphor Icons (MIT license, duotone weight).
// Output: src/icons.json (server) and public/js/icons.js (browser). Re-run after editing NAMES.
const fs = require('fs'); const path = require('path');
const NAMES = ['house','magnifying-glass','fork-knife','calendar-blank','book-open','user-circle','plus','x','check','caret-left','caret-right','arrow-right','arrow-down',
  'camera','tag','target','chart-bar','sparkle','lightbulb','leaf','lock-simple','device-mobile','scales','person-simple-walk','clock','sun-horizon','sun','moon',
  'warning','shield-check','list-checks','list-numbers','heart','flask','arrows-clockwise','drop','cookie','egg','bowl-food','acorn','plant','grains','pencil-simple',
  'check-circle','minus-circle','barcode','note-pencil','cooking-pot','seal-check','flower-lotus','trash','download-simple','sign-out','envelope-simple',
  'shopping-cart-simple','basket','snowflake','package','storefront','copy','check-square','square','printer','warning-circle','clipboard-text','heartbeat','lightning','user-focus'];
const dir = path.join(__dirname, '..', 'node_modules', '@phosphor-icons', 'core', 'assets', 'duotone');
const out = {};
for (const n of NAMES) {
  const svg = fs.readFileSync(path.join(dir, `${n}-duotone.svg`), 'utf8');
  out[n] = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<rect width="256" height="256" fill="none"\/>/, '');
}
fs.writeFileSync(path.join(__dirname, '..', 'src', 'icons.json'), JSON.stringify(out));
fs.writeFileSync(path.join(__dirname, '..', 'public', 'js', 'icons.js'),
  '// Generated by scripts/build-icons.js from Phosphor Icons (MIT).\nwindow.ICONS=' + JSON.stringify(out) + ';\n' +
  'window.icon=function(n,c){var p=window.ICONS[n];return p?\'<svg class="i \'+(c||"")+\'" fill="currentColor" viewBox="0 0 256 256" aria-hidden="true" focusable="false">\'+p+\'</svg>\':"";};\n');
console.log('icons:', Object.keys(out).length);
